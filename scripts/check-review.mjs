#!/usr/bin/env node
// Checks that a pull request that is no longer a draft says how it was reviewed: a "## Review" section in its
// description with a filled "- Ai:" line or "- Bỏ qua: <lý do>" line (profile/REVIEW.md of thienai-workflow).
// Drafts and the AGENTS.md sync bot's PRs (branch chore/sync-agents-md in the same repo) pass.
// Copied from thienai-workflow templates/check-review.mjs; run by .github/workflows/review-check.yml.
// The check turns red; on a private repo without GitHub Pro it cannot block the merge button, so the rule is:
// nobody merges while it is red.
//
//   node scripts/check-review.mjs                 # in GitHub Actions: reads the pull_request event ($GITHUB_EVENT_PATH)
//   node scripts/check-review.mjs --body <file>   # check a description file by hand (treated as ready)
//
// Why: review in a session is a habit, and a habit written only in text gets skipped (STATUS grew back to
// 100 lines within an hour on sakubun, 2026-11-07). CI makes the step visible.
import { readFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SKIP_BRANCHES = ['chore/sync-agents-md'];
// Blanks of the template in profile/REVIEW.md. Only these count as unfilled, so <details>, `Map<K, V>` or
// "n < 40 và m > 3" in a real description are fine.
export const BLANKS = ['<model>', '<ngày>', '<ý>', '<commit>', '<lý do>', '<ai, vì sao>', '<...>'];
const TEMPLATE = 'mẫu ở profile/REVIEW.md của thienai-workflow';
const FOOTER = /^(https:\/\/claude\.ai\/code\/|_Generated by |🤖 Generated with )/;

/** What GitHub shows: no HTML comments (an unclosed one hides the rest), no fenced code blocks. A fence closes
    on a line of the same character at least as long as the opening one (CommonMark); an unclosed one runs to the end. */
function visible(body) {
  const lines = (body || '')
    .replace(/\r\n?/g, '\n')
    .replace(/<!--[\s\S]*?(-->|$)/g, '')
    .split('\n');
  const out = [];
  let fence = null;
  for (const l of lines) {
    const m = /^[ \t]{0,3}(`{3,}|~{3,})/.exec(l);
    if (fence) {
      if (
        m &&
        m[1][0] === fence[0] &&
        m[1].length >= fence.length &&
        /^[ \t]{0,3}[`~]+[ \t]*$/.test(l)
      )
        fence = null;
    } else if (m) fence = m[1];
    else out.push(l);
  }
  return out.join('\n');
}

/** Lines of the "## Review" section, up to the next heading of level 1-2 or the AI footer. null if missing. */
export function reviewLines(body) {
  const lines = visible(body).split('\n');
  const start = lines.findIndex((l) => /^##[ \t]+Review[ \t]*$/.test(l));
  if (start < 0) return null;
  const out = [];
  for (const raw of lines.slice(start + 1)) {
    const l = raw.trim();
    if (/^#{1,2}[ \t]/.test(raw) || FOOTER.test(l)) break;
    if (l && !/^-{3,}$/.test(l)) out.push(l);
  }
  return out;
}

/** Returns the problem in Vietnamese, or '' when the description is fine. */
export function checkReview(body, { draft = false, branch = '', sameRepo = true } = {}) {
  if (draft || (sameRepo && SKIP_BRANCHES.includes(branch))) return '';
  const lines = reviewLines(body);
  if (lines === null)
    return `Mô tả PR chưa có mục "## Review". Review rồi ghi kết quả vào mô tả (${TEMPLATE}), hoặc chuyển PR về nháp.`;
  const blank = lines.find((l) => BLANKS.some((b) => l.replace(/`[^`]*`/g, '').includes(b)));
  if (blank) return `Mục "## Review" còn chỗ chưa điền: "${blank}".`;
  // The value after the label, with bold or italic marks around the label taken off, must have real text.
  const filled = (label) =>
    lines.some((l) => {
      const m = new RegExp(`^(?:[-*+]|\\d+[.)])[ \\t]+[*_]*${label}[ \\t]*:(.*)$`, 'i').exec(l);
      return !!m && /[^\s*_]/.test(m[1]);
    });
  if (!filled('Ai') && !filled('Bỏ qua'))
    return `Mục "## Review" cần một dòng "- Ai: ..." (ai review, khi nào), hoặc "- Bỏ qua: <lý do>" (${TEMPLATE}).`;
  return '';
}

if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  const args = process.argv.slice(2);
  const bi = args.indexOf('--body');
  let body,
    draft = false,
    branch = '',
    sameRepo = true,
    label = 'PR';
  if (bi >= 0) {
    if (!args[bi + 1]) {
      console.error('Thiếu tên file sau --body.');
      process.exit(2);
    }
    body = readFileSync(args[bi + 1], 'utf8');
  } else {
    const path = process.env.GITHUB_EVENT_PATH;
    if (!path) {
      console.error('Không có GITHUB_EVENT_PATH; chạy tay thì dùng --body <file>.');
      process.exit(2);
    }
    const pr = JSON.parse(readFileSync(path, 'utf8')).pull_request;
    if (!pr) {
      console.log('Không phải sự kiện pull request, bỏ qua.');
      process.exit(0);
    }
    body = pr.body;
    draft = !!pr.draft;
    branch = (pr.head && pr.head.ref) || '';
    label = 'PR #' + pr.number;
    sameRepo = !!(
      pr.head &&
      pr.head.repo &&
      pr.base &&
      pr.base.repo &&
      pr.head.repo.full_name === pr.base.repo.full_name
    );
  }
  const problem = checkReview(body, { draft, branch, sameRepo });
  if (problem) {
    console.error(`${label}: ${problem}`);
    process.exit(1);
  }
  const why = draft
    ? 'còn nháp: chưa cần mục Review.'
    : sameRepo && SKIP_BRANCHES.includes(branch)
      ? 'do bot đồng bộ mở: bỏ qua.'
      : 'có mục Review: ổn.';
  console.log(`${label} ${why}`);
}
